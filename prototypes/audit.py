"""Read-only source inventory. Run from any directory; no third-party dependencies."""
from pathlib import Path
from collections import Counter
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'prototypes'


def uncomment(text):
    return re.sub(r'(?<!\\)%[^\n]*', '', text)


def main():
    paths = [ROOT / 'MathNotes.tex', *sorted((ROOT / 'Sections').rglob('*.tex'))]
    sources = {p.relative_to(ROOT).as_posix(): uncomment(p.read_text(encoding='utf-8')) for p in paths}
    combined = '\n'.join(sources.values())
    style = uncomment((ROOT / 'fizztex.sty').read_text(encoding='utf-8'))
    commands = re.findall(r'^\\(?:newcommand|renewcommand)\*?\{\\(\w+)\}|^\\DeclareMathOperator\*?\{\\(\w+)\}', style, re.M)
    macros = sorted({a or b for a, b in commands})
    used = Counter(re.findall(r'\\([A-Za-z]+)', combined))
    chapters = []
    for path in sorted((ROOT / 'Sections').glob('*.tex')):
        src = sources[path.relative_to(ROOT).as_posix()]
        title = re.search(r'\\section\{([^}]+)\}', src)
        if title:
            chapters.append({'title': title[1], 'path': path.relative_to(ROOT).as_posix(),
                             'children': re.findall(r'\\subimport\*?\{([^}]+)\}\{([^}]+)\}', src)})
    references = []
    inline = []
    for name, src in sources.items():
        for match in re.finditer(r'\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}', src):
            references.append({'path': match[1], 'source': name, 'line': src[:match.start()].count('\n') + 1})
        for match in re.finditer(r'\\begin\{(tikzpicture|venndiagram2sets|axis)\}', src):
            inline.append({'source': name, 'type': match[1], 'line': src[:match.start()].count('\n') + 1})
    stats = {
        'tex_files': len(paths), 'tex_lines': sum(len(s.splitlines()) for s in sources.values()),
        'chapters': chapters,
        'headings': dict(Counter(re.findall(r'\\(section|subsection|subsubsection|paragraph)\*?\{', combined))),
        'environments': dict(Counter(re.findall(r'\\begin\{([^}]+)\}', combined)).most_common()),
        'macro_uses': {m: used[m] for m in macros},
        'packages': sorted(set(p.strip() for group in re.findall(r'\\usepackage(?:\[[^\]]*\])?\{([^}]+)\}', combined + style) for p in group.split(','))),
        'labels': re.findall(r'\\label\{([^}]+)\}', combined),
        'refs': re.findall(r'\\(?:eqref|ref|autoref|pageref)\{([^}]+)\}', combined),
        'citations': re.findall(r'\\cite\w*\{([^}]+)\}', combined),
        'bibliography_entries': len(re.findall(r'\\bibitem\{', combined)),
        'image_references': references, 'inline_figures': inline,
        'missing_images': [r for r in references if not (ROOT / r['path']).exists()],
        'source_sha256': {p.relative_to(ROOT).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in [*paths, ROOT / 'fizztex.sty']},
    }
    (OUT / 'audit-data.json').write_text(json.dumps(stats, indent=2) + '\n', encoding='utf-8')
    lines = ['# Figure inventory', '',
             'Generated by `python prototypes/audit.py`. Counts exclude commented LaTeX. Raster recommendations are triage based on filenames and source context, not a completed visual or rights review.', '',
             'No per-image attribution or licensing records were found. All raster assets are therefore **uncertain provenance** (not assumed original or automatically cleared). The bibliography names courses and MIT OCW but does not map sources or permissions to individual images. Inline TeX figures appear locally authored/editable; authorship still needs confirmation. **Nothing is approved for publication by this inventory.**', '',
             'Preserve every original. Redraw from the underlying mathematics only after checking the meaning; export SVG for HTML and PDF for print. Python is appropriate for plotted functions/data; TikZ for geometry, sets and circuits; hand-edited SVG for simple illustrations. Do not vectorize a screenshot and treat that as quality or rights clearance.', '',
             '## Raster files', '',
             '| Original file | Type | Used by | Provenance | Recommended rendering | Manual review |',
             '|---|---|---|---|---|---|']
    for p in sorted((ROOT / 'Images').rglob('*')):
        if not p.is_file():
            continue
        name = p.relative_to(ROOT).as_posix()
        refs = [r for r in references if r['path'] == name]
        uses = ', '.join(f"[{r['source']}:{r['line']}]({r['source']})" for r in refs) or 'Not referenced'
        lower = p.stem.lower()
        render = 'Python → SVG/PDF' if any(w in lower for w in ('graph', 'plot', 'portrait', 'sinc', 'resonance', 'beats', 'response', 'amplitude', 'histogram', 'concavity', 'sinx', 'cotx', 'tanx', 'secx', 'cscx')) else 'TikZ → SVG/PDF'
        if p.parent.name == 'Phil120Pictures':
            render = 'Redraw as semantic logic/table; SVG if diagram'
        lines.append(f'| [{name}]({name.replace(" ", "%20")}) | {p.suffix[1:].upper()} raster | {uses} | Uncertain | {render}; preserve original | Yes: provenance, notation, legibility |')
    lines += ['', '## Embedded vector sources', '', '| Original location | Type | Provenance | Recommended rendering | Manual review |', '|---|---|---|---|---|']
    for fig in inline:
        lines.append(f"| [{fig['source']}:{fig['line']}]({fig['source']}) | {fig['type']} | Appears original; unconfirmed | Preserve TeX; compile SVG/PDF | Yes: authorship, labels, mathematical geometry |")
    lines += ['', '## Publication gate', '',
              'For each asset, record author, source URL, license/permission, attribution text, semantic description, reviewer and approval date before adding it to a public build. Exclude unapproved assets from the public build rather than silently removing figures from the textbook. A blocked figure blocks that section’s publication. The local prototype uses only the existing intersection Venn diagram at Probability/Foundations lines 18–20, with explicit local-preview status.', '',
              f"Totals: {sum(p.is_file() for p in (ROOT / 'Images').rglob('*'))} raster files, {len(references)} graphic inclusions, {len(inline)} embedded figures; {len(stats['missing_images'])} missing graphic paths.", '']
    (ROOT / 'FIGURE_INVENTORY.md').write_text('\n'.join(lines), encoding='utf-8')
    print(json.dumps({k: v for k, v in stats.items() if k not in ('source_sha256', 'image_references', 'inline_figures')}, indent=2))


if __name__ == '__main__':
    main()
