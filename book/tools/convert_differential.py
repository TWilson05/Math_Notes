"""Convert the complete Differential Calculus source into MyST.

This is intentionally a narrow, auditable structural converter. It does not
rewrite mathematics; it translates headings, display wrappers, lists, figures,
and a few print-only wrappers while leaving unknown commands visible for review.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "book" / "differential-calculus"
SRC = ROOT / "Sections" / "Differential_Calculus"

TITLE = {
    "Limits_and_Continuity": "Limits and Continuity",
    "Differentiation": "Differentiation",
    "Differentiation_Techniques": "Differentiation Techniques",
    "Approximations": "Approximations",
    "Graphing": "Graphing with Derivatives",
    "Applications_of_Derivatives": "Applications of Derivatives",
}


def inline(line: str, preserve_breaks: bool = False) -> str:
    replacements = [
        (r"\\textit\{([^{}]*)\}", r"*\1*"),
        (r"\\textbf\{([^{}]*)\}", r"**\1**"),
        (r"\\emph\{([^{}]*)\}", r"*\1*"),
        (r"\\underline\{([^{}]*)\}", r"\1"),
        (r"\\centerline\{", ""),
        (r"\\vspace\{[^{}]*\}", ""),
        (r"\\hspace\{[^{}]*\}", ""),
    ]
    for pattern, replacement in replacements:
        line = re.sub(pattern, replacement, line)
    # Keep escaped ampersands for the LaTeX builder; unescaped `&` is an
    # alignment tab and can break otherwise valid inline mathematics.
    # Forced print line breaks are paragraph boundaries in MyST.
    line = line.replace(r"\text{Find the angle between $\brangle{1,2}$ and $\brangle{1,1}$}", r"\text{Find the angle between }\brangle{1,2}\text{ and }\brangle{1,1}")
    line = line.replace(r"\text{Find the projection of $\brangle{2,3}$ onto $\brangle{2,1}$}", r"\text{Find the projection of }\brangle{2,3}\text{ onto }\brangle{2,1}")
    line = line.replace(r"\text{Find all $\vec{x}$ such that $A^T\vec{x}=0$}", r"\text{Find all }\ensuremath{\vec{x}}\text{ such that }A^T\ensuremath{\vec{x}}=0")
    line = line.replace(r"\text{we can break this up into two different focre fields $\vec{F}_1$ and $\vec{F}_2$}", r"\text{we can break this up into two different focre fields }\ensuremath{\vec{F}_1}\text{ and }\ensuremath{\vec{F}_2}")
    line = line.replace(r"\text{$r$ is small}", r"\text{\ensuremath{r} is small}")
    line = line.replace(r"\text{$g$ is entire because $f$ is entire}", r"\text{\ensuremath{g} is entire because \ensuremath{f} is entire}")
    line = line.replace(r"\text{$A$ is a defective matrix}", r"\text{\ensuremath{A} is a defective matrix}")
    line = line.replace(r"\text{$n$ is a whole number}", r"\text{\ensuremath{n} is a whole number}")
    line = line.replace(r"\text{$\vec{F}$ is undefined at $(0,0)$, meaning it is not simply connected}", r"\text{\ensuremath{\vec{F}} is undefined at \ensuremath{(0,0)}, meaning it is not simply connected}")
    line = line.replace(r"\text{solve for $h(y)$ and then $\phi(x,y)+h(y)$ will be the solution}", r"\text{solve for }\ensuremath{h(y)}\text{ and then }\ensuremath{\phi(x,y)+h(y)}\text{ will be the solution}")
    if preserve_breaks:
        # The original occasionally nests `$...$` inside `\text{...}` while
        # already inside an aligned display. MyST wraps the whole display for
        # LaTeX output, so nested dollar delimiters create invalid TeX. The
        # surrounding \text is already in math mode; remove only the delimiters.
        # Preserve inline math nested inside \text{...}; dollar delimiters
        # cannot be nested in the LaTeX generated by Sphinx, while
        # \ensuremath keeps the original exponent/variable semantics.
        line = line.replace("$e^0=1$", r"\ensuremath{e^0=1}")
        nested = re.compile(r"\\text\{([^{}]*?)\$([^$]+)\$([^{}]*?)\}")
        while nested.search(line):
            line = nested.sub(r"\\text{\1\\ensuremath{\2}\3}", line)
        line = re.sub(r"(because we know )e\^0=1", r"\1\\ensuremath{e^0=1}", line)
        line = line.replace("$", "")
        line = line.replace(r"\(", "").replace(r"\)", "")
        line = line.replace(r"\ngtr", r"\not>").replace(r"\nless", r"\not<")
    else:
        line = re.sub(r"\\\\+", "", line)
        # A few legacy prose lines use $$...$$ for inline displays. MyST's
        # block parser treats those as literal delimiters; normalize only the
        # delimiters while leaving the enclosed expression unchanged.
        line = line.replace("$$", "$")
    # Close a centerline wrapper when it appears around an image.
    line = re.sub(r"\}\s*$", "", line) if "includegraphics" in line else line
    return line.rstrip()


def figure_directive(path: str, options: str = "", occurrence: int = 1) -> list[str]:
    parts = Path(path).parts
    rel = Path(*parts[1:]) if parts and parts[0].lower() == "images" else Path(path)
    source = "../figures/original/" + rel.as_posix().replace(" ", "")
    label = Path(path).stem.lower().replace(" ", "-") + (f"-{occurrence}" if occurrence > 1 else "")
    width = "85%"
    if "width=0.95" in options or "scale=0.9" in options:
        width = "95%"
    elif "scale=0.3" in options or "scale=0.2" in options:
        width = "55%"
    return [
        f"```{{figure}} {source}",
        f":name: fig-differential-{label}",
        f":alt: Existing mathematics notes figure ({Path(path).stem}). Review provenance before publication.",
        f":width: {width}",
        "",
        f"Existing source figure: `{path}`. It is preserved for review and is not assumed publication-cleared.",
        "```",
        "",
    ]


def convert(path: Path) -> str:
    lines = path.read_text(encoding="utf-8").splitlines()
    source_title = next((m.group(1) for m in (re.search(r"\\subsection\{([^}]*)\}", line) for line in lines) if m), None)
    page_title = TITLE.get(path.stem, source_title or path.stem.replace("_", " "))
    out: list[str] = [f"# {page_title}", "", f"<!-- Source: [{path.relative_to(ROOT).as_posix()}](../../{path.relative_to(ROOT).as_posix()}) -->", ""]
    state: str | None = None
    list_depth = 0
    figure_seen: dict[str, int] = {}
    for raw in lines:
        line = raw.rstrip()
        stripped = line.strip()
        if not stripped or stripped.startswith("%"):
            if out and out[-1] != "":
                out.append("")
            continue
        m = re.match(r"\\subsection\{([^}]*)\}", stripped)
        if m:
            continue
        m = re.match(r"\\subsubsection\{(.+?)\}", stripped)
        if m:
            out.extend([f"## {m.group(1)}", ""])
            continue
        m = re.search(r"\\includegraphics(?:\[([^]]*)\])?\{([^}]+)\}", stripped)
        if m:
            figure_seen[m.group(2)] = figure_seen.get(m.group(2), 0) + 1
            out.extend(figure_directive(m.group(2), m.group(1) or "", figure_seen[m.group(2)]))
            continue
        if stripped.startswith(r"\begin{align*") or stripped.startswith(r"\begin{flalign*"):
            state = "math"
            if out and out[-1] != "":
                out.append("")
            out.extend(["$$", r"\begin{aligned}"])
            continue
        if r"\x_1" in stripped and r"\matrixx" in stripped:
            out.extend(["", "```latex", line, "```", ""])
            continue
        if stripped.startswith("$$") and stripped.endswith("$$") and stripped.count("$$") == 2 and len(stripped) > 4:
            body = stripped[2:-2]
            if out and out[-1] != "":
                out.append("")
            out.extend(["$$", body, "$$", ""])
            continue
        if stripped.startswith(r"\[") and stripped.endswith(r"\]") and len(stripped) > 4:
            body = stripped[2:-2]
            if out and out[-1] != "":
                out.append("")
            out.extend(["$$", body, "$$", ""])
            continue
        if stripped.startswith(r"\end{align*") or stripped.startswith(r"\end{flalign*"):
            out.extend([r"\end{aligned}", "$$", ""])
            state = None
            continue
        if stripped == "$$" and state == "math":
            out.extend(["$$", ""])
            state = None
            continue
        if stripped == r"\[" or (stripped == "$$" and state != "math"):
            state = "math"
            if out and out[-1] != "":
                out.append("")
            out.append("$$")
            continue
        if stripped == r"\]" and state == "math":
            out.extend(["$$", ""])
            state = None
            continue
        m = re.match(r"\\begin\{(itemize|enumerate|description)\}", stripped)
        if m:
            list_depth += 1
            state = m.group(1)
            out.append("")
            continue
        if re.match(r"\\end\{(itemize|enumerate|description)\}", stripped):
            list_depth = max(0, list_depth - 1)
            state = None if list_depth == 0 else state
            out.append("")
            continue
        if stripped.startswith(r"\item"):
            value = stripped[len(r"\item"):].strip()
            if value.startswith("[") and "]" in value:
                value = value.replace("]", "]:", 1)
            out.append(f"- {inline(value)}")
            continue
        if stripped.startswith(r"\begin{tabular"):
            if "p{" in stripped:
                state = "tabular-code"
                out.extend(["", "```latex", stripped])
            else:
                state = "math"
                out.extend(["$$", stripped.replace(r"\begin{tabular}", r"\begin{array}")])
            continue
        if stripped.startswith(r"\end{tabular"):
            if state == "tabular-code":
                out.extend([stripped, "```", ""])
            else:
                out.extend([r"\end{array}", "$$", ""])
            state = None
            continue
        if stripped in (r"\begin{center}", r"\end{center}"):
            continue
        if stripped.startswith(r"\newcommand"):
            # Local command declarations are not content; macro support is centralized.
            continue
        if r"\argument" in stripped:
            out.extend(["", "```latex", line, "```", ""])
            continue
        if r"\matrixx{1 & t_0" in stripped or (r"\matrixx" in stripped and "\\\\" not in stripped and stripped.count("&") > 3):
            out.extend(["", "```latex", line, "```", ""])
            continue
        if r"\matrixx{(x_1a_1+x_2a_2)a_1\x_1" in stripped:
            out.extend(["", "```latex", line, "```", ""])
            continue
        out.append(inline(line, preserve_breaks=state == "math"))
    while out and out[-1] == "":
        out.pop()
    normalized: list[str] = []
    for item in out:
        if item == "$$" and normalized and normalized[-1] != "":
            normalized.append("")
        normalized.append(item)
    return "\n".join(normalized) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for source in sorted(SRC.glob("*.tex")):
        target = OUT / f"{source.stem}.md"
        target.write_text(convert(source), encoding="utf-8")
    index = ["# Differential Calculus", "", "This chapter preserves the complete six-file Differential Calculus course. Each page records its original TeX source in an HTML comment for traceability.", "", "```{toctree}", ":maxdepth: 2", "", *[p.stem for p in sorted(SRC.glob("*.tex"))], "```", ""]
    (OUT / "index.md").write_text("\n".join(index), encoding="utf-8")
    print(f"Converted {len(list(SRC.glob('*.tex')))} Differential Calculus files to {OUT}")


if __name__ == "__main__":
    main()
